// Admin approval; sign out/in while offline; restart offline; auto-resume.
const h = require('./helpers.cjs')

h.run('AUTH', async () => {
  const A = await h.launch('A', { viaRelay: true })
  const B = await h.launch('B')
  await h.signIn(A, h.TECH1)
  await h.signIn(B, h.TECH2, h.PW, { expectDashboard: false })
  await B.page.getByText('Waiting for approval').waitFor({ timeout: 60000 })
  await h.nav(A, 'Settings')
  await A.page.getByText('1 waiting for approval').waitFor({ timeout: 30000 })
  await A.page.getByRole('button', { name: 'Approve' }).click()
  const t = Date.now()
  await B.page.getByText('Welcome back').waitFor({ timeout: 60000 })
  h.log(`approval unlocked the new technician in ${((Date.now() - t) / 1000).toFixed(1)}s`)

  // offline: create, sign out, wrong password, other person, sign back in
  await h.nav(A, 'Customers')
  h.setNetwork(false); await h.browserOffline(A, true)
  await A.page.getByTestId('sync-indicator').filter({ hasText: 'Offline' }).first().waitFor({ timeout: 30000 })
  await A.page.getByRole('button', { name: 'New customer' }).first().click()
  await A.page.getByRole('dialog').getByLabel('Company name *').fill('Offline Customer Co')
  await A.page.getByRole('dialog').getByRole('button', { name: 'Save' }).click()
  await A.page.getByRole('heading', { name: 'Offline Customer Co' }).waitFor()
  await h.nav(A, 'Settings')
  await A.page.getByRole('button', { name: 'Sign out' }).first().click()
  await A.page.getByRole('dialog').getByRole('button', { name: 'Sign out' }).click()
  await A.page.getByRole('button', { name: 'Sign in' }).waitFor()
  h.check((await A.page.getByLabel('Email').inputValue()) === h.TECH1, 'email not prefilled after sign-out')
  await h.signIn(A, h.TECH1, 'wrong-password', { expectDashboard: false })
  await A.page.getByText('Incorrect password.').waitFor()
  await h.signIn(A, h.TECH2, h.PW, { expectDashboard: false })
  await A.page.getByText(`only ${h.TECH1} can sign in`).waitFor()
  await h.signIn(A, h.TECH1)
  await h.nav(A, 'Customers'); await A.page.getByText('Offline Customer Co').waitFor()
  h.log('offline: sign-out kept data; wrong password and other person refused; sign-in worked')

  // restart while offline and signed out
  await h.nav(A, 'Settings')
  await A.page.getByRole('button', { name: 'Sign out' }).first().click()
  await A.page.getByRole('dialog').getByRole('button', { name: 'Sign out' }).click()
  await A.app.close()
  const A2 = await h.launch('A', { viaRelay: true }); await h.browserOffline(A2, true); await A2.page.reload()
  await h.signIn(A2, h.TECH1)
  h.log('after a restart, signed in fully offline')

  // back online: resumes by itself, nothing rejected
  h.setNetwork(true); await h.browserOffline(A2, false)
  await h.nav(B, 'Customers')
  await B.page.getByText('Offline Customer Co').waitFor({ timeout: 90000 })
  await h.nav(A2, 'Settings')
  await A2.page.getByTestId('pending-count').filter({ hasText: /^0$/ }).waitFor({ timeout: 30000 })
  h.check(!(await A2.page.getByText('Changes the server rejected').isVisible()), 'offline change was rejected instead of uploaded')
  h.log('back online: synced by itself, nothing rejected')
  await A2.app.close(); await B.app.close()
})
